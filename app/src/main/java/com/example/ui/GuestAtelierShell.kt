/**
 * Unauthenticated local-session ViewModel so users open directly onto the Modest Tailor Studio
 * main page without being blocked by Sign In / Sign Up. Strictly avoids any Firestore access;
 * Firebase AI Logic (via App Check) and in-memory collections run immediately.
 */
class GuestAtelierViewModel(
    private val aiService: TailorAiService,
    private val dailyOutfitCache: DailyOutfitCache? = null,
    initialProfile: StyleProfile = StyleProfile(
        userId = GUEST_USER_ID,
        displayName = "Guest Stylist",
        cityOrArea = "Oakbrook & Promenade"
    ),
    autoGenerateDailyEdit: Boolean = true
) : ViewModel() {

    private var lastEvaluatedDailyKey: String? = null
    private var dailyEditJob: Job? = null

    private val _profile = MutableStateFlow(initialProfile)
    val profileState: StateFlow<DataUiState<StyleProfile>> = _profile
        .map<StyleProfile, DataUiState<StyleProfile>> { DataUiState.Success(it) }
        .stateIn(
            scope = viewModelScope,
            started = SharingStarted.WhileSubscribed(5_000L),
            initialValue = DataUiState.Success(initialProfile)
        )

    private val _inventory = MutableStateFlow(
        FashionCatalogConstants.starterBoutiqueItems(
            userId = GUEST_USER_ID,
            district = initialProfile.cityOrArea
        ).mapIndexed { index, item ->
            item.copy(id = "guest_starter_$index")
        }
    )
    val inventoryState: StateFlow<DataUiState<List<InventoryItem>>> = _inventory
        .map<List<InventoryItem>, DataUiState<List<InventoryItem>>> { DataUiState.Success(it) }
        .stateIn(
            scope = viewModelScope,
            started = SharingStarted.WhileSubscribed(5_000L),
            initialValue = DataUiState.Success(_inventory.value)
        )

    private val _savedOutfits = MutableStateFlow<List<SavedOutfit>>(emptyList())
    val savedOutfitsState: StateFlow<DataUiState<List<SavedOutfit>>> = _savedOutfits
        .map<List<SavedOutfit>, DataUiState<List<SavedOutfit>>> { DataUiState.Success(it) }
        .stateIn(
            scope = viewModelScope,
            started = SharingStarted.WhileSubscribed(5_000L),
            initialValue = DataUiState.Success(emptyList())
        )

    private val _feedback = MutableStateFlow<List<OutfitFeedback>>(emptyList())

    val dailyFeedbackVotes: StateFlow<Map<String, FeedbackVote>> = _feedback
        .map { list ->
            list.mapNotNull { fb ->
                val vote = FeedbackVote.fromRaw(fb.vote) ?: return@mapNotNull null
                "${fb.dateKey}|${fb.outfitTitle.trim().take(120)}" to vote
            }.toMap()
        }
        .stateIn(
            scope = viewModelScope,
            started = SharingStarted.WhileSubscribed(5_000L),
            initialValue = emptyMap()
        )

    val savedLookTitles: StateFlow<Set<String>> = _savedOutfits
        .map { list -> list.map { it.title.trim().take(120) }.toSet() }
        .stateIn(
            scope = viewModelScope,
            started = SharingStarted.WhileSubscribed(5_000L),
            initialValue = emptySet()
        )

    val savedOutfitsCount: StateFlow<Int> = _savedOutfits
        .map { it.size }
        .stateIn(
            scope = viewModelScope,
            started = SharingStarted.WhileSubscribed(5_000L),
            initialValue = 0
        )

    private val _dailyEditState = MutableStateFlow<DailyEditUiState>(DailyEditUiState.Idle)
    val dailyEditState: StateFlow<DailyEditUiState> = _dailyEditState.asStateFlow()

    private val _stylistState = MutableStateFlow<StylistUiState>(StylistUiState.Idle)
    val stylistState: StateFlow<StylistUiState> = _stylistState.asStateFlow()

    private val _garmentScanState = MutableStateFlow<GarmentScanUiState>(GarmentScanUiState.Idle)
    val garmentScanState: StateFlow<GarmentScanUiState> = _garmentScanState.asStateFlow()

    private val _statusMessage = MutableStateFlow<String?>(null)
    val statusMessage: StateFlow<String?> = _statusMessage.asStateFlow()

    private val _isSavingProfile = MutableStateFlow(false)
    val isSavingProfile: StateFlow<Boolean> = _isSavingProfile.asStateFlow()

    private val _savingOutfitTitles = MutableStateFlow<Set<String>>(emptySet())
    val savingOutfitTitles: StateFlow<Set<String>> = _savingOutfitTitles.asStateFlow()

    private val _submittingFeedbackTitles = MutableStateFlow<Set<String>>(emptySet())
    val submittingFeedbackTitles: StateFlow<Set<String>> = _submittingFeedbackTitles.asStateFlow()

    init {
        if (autoGenerateDailyEdit) {
            viewModelScope.launch {
                combine(_profile, _inventory) { profile, inventory -> profile to inventory }
                    .collect { (profile, inventory) ->
                        ensureDailyEditForToday(
                            profile = profile,
                            inventory = inventory,
                            forceRefresh = false
                        )
                    }
            }
        }
    }

    fun dismissStatusMessage() {
        _statusMessage.value = null
    }

    fun refreshDailyEdit() {
        ensureDailyEditForToday(
            profile = _profile.value,
            inventory = _inventory.value,
            forceRefresh = true
        )
    }

    private fun ensureDailyEditForToday(
        profile: StyleProfile,
        inventory: List<InventoryItem>,
        forceRefresh: Boolean
    ) {
        val now = Date()
        val dateKey = SimpleDateFormat("yyyy-MM-dd", Locale.US).format(now)
        val dateDisplay = SimpleDateFormat("MMM d", Locale.getDefault()).format(now)
        val dayOfWeek = SimpleDateFormat("EEEE", Locale.getDefault()).format(now)
        val fingerprint = profile.preferenceFingerprint()
        val combinedKey = "$dateKey|$fingerprint"

        if (!forceRefresh && lastEvaluatedDailyKey == combinedKey) return

        if (!forceRefresh) {
            val cached = dailyOutfitCache?.loadIfValid(GUEST_USER_ID, dateKey, fingerprint)
            if (cached != null) {
                lastEvaluatedDailyKey = combinedKey
                _dailyEditState.value = DailyEditUiState.Success(cached, isFromCache = true)
                return
            }
        }

        lastEvaluatedDailyKey = combinedKey
        dailyEditJob?.cancel()
        dailyEditJob = viewModelScope.launch {
            _dailyEditState.value = DailyEditUiState.Loading
            try {
                val dailyRecommendation = aiService.generateDailyPersonalizedEdit(
                    profile = profile,
                    availableInventory = inventory,
                    dateKey = dateKey,
                    dateDisplay = "$dayOfWeek, $dateDisplay",
                    dayOfWeek = dayOfWeek,
                    recentFeedback = _feedback.value
                )
                if (dailyRecommendation.outfits.isNotEmpty()) {
                    dailyOutfitCache?.save(GUEST_USER_ID, fingerprint, dailyRecommendation)
                    _dailyEditState.value = DailyEditUiState.Success(
                        recommendation = dailyRecommendation,
                        isFromCache = false
                    )
                } else {
                    _dailyEditState.value = DailyEditUiState.Error(
                        "Daily AI returned no outfits. Tap Retry to refresh."
                    )
                }
            } catch (e: TimeoutCancellationException) {
                Log.e(TAG, "Guest daily edit timed out", e)
                lastEvaluatedDailyKey = null
                _dailyEditState.value = DailyEditUiState.Error(
                    "Daily curation timed out after 60 seconds. Tap Retry to try again."
                )
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                val rootDetail = e.cause?.message?.takeIf { it.isNotBlank() }
                Log.e(TAG, "Guest daily edit failed: ${e.message} (cause=$rootDetail)", e)
                lastEvaluatedDailyKey = null
                _dailyEditState.value = DailyEditUiState.Error(
                    buildString {
                        append(e.localizedMessage ?: "Unable to generate today's personalized edit.")
                        if (!rootDetail.isNullOrBlank()) {
                            append(" (")
                            append(rootDetail)
                            append(")")
                        }
                    }
                )
            }
        }
    }

    fun generateOutfits(occasion: String, season: String, customRequest: String) {
        viewModelScope.launch {
            _stylistState.value = StylistUiState.Loading
            try {
                val recommendation = aiService.generateOutfitRecommendations(
                    profile = _profile.value,
                    availableInventory = _inventory.value,
                    occasion = occasion,
                    season = season,
                    customRequest = customRequest,
                    recentFeedback = _feedback.value
                )
                if (recommendation.outfits.isNotEmpty()) {
                    _stylistState.value = StylistUiState.Success(recommendation)
                } else {
                    _stylistState.value = StylistUiState.Error(
                        "Tailor AI returned no outfits. Try adjusting your occasion or request."
                    )
                }
            } catch (e: TimeoutCancellationException) {
                _stylistState.value = StylistUiState.Error(
                    "Styling timed out after 60 seconds. Please try again."
                )
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Guest outfit generation failed", e)
                _stylistState.value = StylistUiState.Error(
                    e.localizedMessage ?: "Unable to generate outfit recommendations."
                )
            }
        }
    }

    fun toggleClosetBookmark(outfit: AiCuratedOutfit) {
        val normalizedTitle = outfit.title.trim().take(120)
        val existingMatch = _savedOutfits.value.firstOrNull {
            it.title.trim().take(120) == normalizedTitle
        }
        if (existingMatch != null) {
            _savedOutfits.value = _savedOutfits.value.filterNot { it.id == existingMatch.id }
            _statusMessage.value = "Removed \"${outfit.title}\" from your Closet."
        } else {
            val saved = SavedOutfit(
                id = "guest_outfit_${UUID.randomUUID()}",
                userId = GUEST_USER_ID,
                title = outfit.title,
                audience = outfit.audience,
                occasion = outfit.occasion,
                trendHighlight = outfit.trendHighlight,
                coverageVerification = outfit.coverageVerification,
                stylingNotes = outfit.stylingNotes,
                matchedPieces = outfit.matchedPieces,
                boutiqueSources = outfit.boutiqueSources,
                favorite = false
            )
            _savedOutfits.value = listOf(saved) + _savedOutfits.value
            _statusMessage.value = "Saved \"${outfit.title}\" to your Closet."
        }
    }

    fun submitDailyOutfitFeedback(
        outfit: AiCuratedOutfit,
        vote: FeedbackVote,
        dateKey: String
    ) {
        val normalizedTitle = outfit.title.trim().take(120)
        val safeDateKey = dateKey.trim().ifBlank {
            SimpleDateFormat("yyyy-MM-dd", Locale.US).format(Date())
        }.take(20)
        val docId = outfitFeedbackDocId(safeDateKey, normalizedTitle)

        val existingFeedback = _feedback.value.firstOrNull {
            it.id == docId || (it.dateKey == safeDateKey && it.outfitTitle.trim().take(120) == normalizedTitle)
        }
        val existingVote = FeedbackVote.fromRaw(existingFeedback?.vote)

        if (existingFeedback != null && existingVote == vote) {
            _feedback.value = _feedback.value.filterNot { it.id == existingFeedback.id }
            _statusMessage.value = "Cleared rating for \"${outfit.title}\"."
        } else {
            val feedback = OutfitFeedback(
                id = docId,
                userId = GUEST_USER_ID,
                outfitTitle = normalizedTitle,
                vote = vote.name,
                dateKey = safeDateKey,
                audience = outfit.audience,
                occasion = outfit.occasion,
                trendHighlight = outfit.trendHighlight,
                matchedPieces = outfit.matchedPieces
            )
            _feedback.value = listOf(feedback) + _feedback.value.filterNot { it.id == docId }
            _statusMessage.value = if (vote == FeedbackVote.UP) {
                "Saved Thumbs Up! Future AI outfits will lean toward styles like this."
            } else {
                "Saved Thumbs Down! Future AI outfits will steer in a different direction."
            }
        }
    }

    fun toggleOutfitFavorite(outfitId: String, favorite: Boolean) {
        _savedOutfits.value = _savedOutfits.value.map { outfit ->
            if (outfit.id == outfitId) outfit.copy(favorite = favorite) else outfit
        }
    }

    fun updateSavedOutfitNotes(
        outfitId: String,
        title: String,
        stylingNotes: String,
        favorite: Boolean
    ) {
        _savedOutfits.value = _savedOutfits.value.map { outfit ->
            if (outfit.id == outfitId) {
                outfit.copy(title = title, stylingNotes = stylingNotes, favorite = favorite)
            } else {
                outfit
            }
        }
        _statusMessage.value = "Updated closet notes."
    }

    fun deleteSavedOutfit(outfitId: String) {
        _savedOutfits.value = _savedOutfits.value.filterNot { it.id == outfitId }
        _statusMessage.value = "Removed ensemble from Saved Closet."
    }

    fun seedStarterBoutique() {
        val district = _profile.value.cityOrArea
        val starter = FashionCatalogConstants.starterBoutiqueItems(
            userId = GUEST_USER_ID,
            district = district
        ).mapIndexed { index, item ->
            item.copy(id = "guest_starter_${System.currentTimeMillis()}_$index")
        }
        _inventory.value = starter
        _statusMessage.value = "Loaded ${starter.size} Ladies, Teens & Girls pieces into Local Inventory."
    }

    fun addInventoryItem(item: InventoryItem) {
        val added = item.copy(
            id = "guest_item_${UUID.randomUUID()}",
            userId = GUEST_USER_ID
        )
        _inventory.value = listOf(added) + _inventory.value
        _statusMessage.value = "Added \"${item.name}\" to Local Inventory."
    }

    fun toggleInventoryStock(itemId: String, inStock: Boolean) {
        _inventory.value = _inventory.value.map { item ->
            if (item.id == itemId) item.copy(inStock = inStock) else item
        }
    }

    fun deleteInventoryItem(itemId: String) {
        _inventory.value = _inventory.value.filterNot { it.id == itemId }
        _statusMessage.value = "Removed garment from Local Inventory."
    }

    fun analyzeGarmentBitmap(bitmap: Bitmap) {
        viewModelScope.launch {
            _garmentScanState.value = GarmentScanUiState.Scanning
            try {
                val result = aiService.analyzeGarmentPhoto(bitmap, _profile.value)
                _garmentScanState.value = GarmentScanUiState.Success(result)
            } catch (e: TimeoutCancellationException) {
                _garmentScanState.value = GarmentScanUiState.Error(
                    "Photo analysis timed out after 60 seconds."
                )
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Guest garment photo scan failed", e)
                _garmentScanState.value = GarmentScanUiState.Error(
                    e.localizedMessage ?: "Unable to analyze garment photo."
                )
            }
        }
    }

    fun clearGarmentScan() {
        _garmentScanState.value = GarmentScanUiState.Idle
    }

    fun saveProfile(
        profile: StyleProfile,
        onSaved: () -> Unit = {},
        onProfileChanged: (StyleProfile) -> Unit = {}
    ) {
        val normalized = profile.copy(userId = GUEST_USER_ID)
        _profile.value = normalized
        onProfileChanged(normalized)
        _statusMessage.value = "Updated your sizes, palette, and modesty preferences."
        onSaved()
    }

    private companion object {
        const val TAG = "GuestAtelierVM"
        const val GUEST_USER_ID = "guest"
    }
}

@Composable
internal fun GuestAtelierShell(
    initialDraftProfile: StyleProfile?,
    onGuestProfileUpdated: (StyleProfile) -> Unit,
    incomingDeepLinkUri: Uri?,
    onConsumeDeepLink: () -> Unit,
    onRequestSignIn: () -> Unit
) {
    val viewModel: GuestAtelierViewModel = viewModel(
        key = "guest_atelier_session",
        factory = viewModelFactory {
            initializer {
                val app = checkNotNull(this[APPLICATION_KEY]) {
                    "APPLICATION_KEY missing from CreationExtras"
                }
                GuestAtelierViewModel(
                    aiService = TailorAiService(),
                    dailyOutfitCache = DailyOutfitCache(app.applicationContext),
                    initialProfile = initialDraftProfile ?: StyleProfile(
                        userId = "guest",
                        displayName = "Guest Stylist",
                        cityOrArea = "Oakbrook & Promenade"
                    )
                )
            }
        }
    )

    val profileState by viewModel.profileState.collectAsStateWithLifecycle()
    val inventoryState by viewModel.inventoryState.collectAsStateWithLifecycle()
    val savedOutfitsState by viewModel.savedOutfitsState.collectAsStateWithLifecycle()
    val dailyEditState by viewModel.dailyEditState.collectAsStateWithLifecycle()
    val stylistState by viewModel.stylistState.collectAsStateWithLifecycle()
    val garmentScanState by viewModel.garmentScanState.collectAsStateWithLifecycle()
    val savedLookTitles by viewModel.savedLookTitles.collectAsStateWithLifecycle()
    val savingOutfitTitles by viewModel.savingOutfitTitles.collectAsStateWithLifecycle()
    val dailyFeedbackVotes by viewModel.dailyFeedbackVotes.collectAsStateWithLifecycle()
    val submittingFeedbackTitles by viewModel.submittingFeedbackTitles.collectAsStateWithLifecycle()
    val savedOutfitsCount by viewModel.savedOutfitsCount.collectAsStateWithLifecycle()
    val statusMessage by viewModel.statusMessage.collectAsStateWithLifecycle()
    val isSavingProfile by viewModel.isSavingProfile.collectAsStateWithLifecycle()

    AtelierShellContent(
        isAuthenticated = false,
        userEmail = null,
        profileState = profileState,
        inventoryState = inventoryState,
        savedOutfitsState = savedOutfitsState,
        dailyEditState = dailyEditState,
        stylistState = stylistState,
        garmentScanState = garmentScanState,
        savedLookTitles = savedLookTitles,
        savingOutfitTitles = savingOutfitTitles,
        dailyFeedbackVotes = dailyFeedbackVotes,
        submittingFeedbackTitles = submittingFeedbackTitles,
        savedOutfitsCount = savedOutfitsCount,
        statusMessage = statusMessage,
        isSavingProfile = isSavingProfile,
        incomingDeepLinkUri = incomingDeepLinkUri,
        onConsumeDeepLink = onConsumeDeepLink,
        onDismissStatusMessage = viewModel::dismissStatusMessage,
        onRefreshDailyEdit = viewModel::refreshDailyEdit,
        onGenerateOutfits = viewModel::generateOutfits,
        onSaveOutfit = viewModel::toggleClosetBookmark,
        onDailyOutfitFeedback = viewModel::submitDailyOutfitFeedback,
        onSeedStarterInventory = viewModel::seedStarterBoutique,
        onAddInventoryItem = viewModel::addInventoryItem,
        onToggleInventoryStock = viewModel::toggleInventoryStock,
        onDeleteInventoryItem = viewModel::deleteInventoryItem,
        onAnalyzeGarmentBitmap = viewModel::analyzeGarmentBitmap,
        onClearGarmentScan = viewModel::clearGarmentScan,
        onToggleOutfitFavorite = viewModel::toggleOutfitFavorite,
        onUpdateSavedOutfitNotes = viewModel::updateSavedOutfitNotes,
        onDeleteSavedOutfit = viewModel::deleteSavedOutfit,
        onSaveProfile = { updated, onSaved ->
            viewModel.saveProfile(
                profile = updated,
                onSaved = onSaved,
                onProfileChanged = onGuestProfileUpdated
            )
        },
        onSignInClick = onRequestSignIn,
        onSignOutClick = {}
    )
}
